#!/usr/bin/env bash
# test-sync-codex-agents.sh: offline harness for sync-codex-agents.py.
# Checks the repository's own contracts are in sync, then breaks a scratch copy in
# every way --check must refuse.
set -u
HERE="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
. "$HERE/../hooks/harness-lib.sh"
KIT_ROOT="$(cd -- "$HERE/../.." && pwd -P)"
SYNC="$HERE/sync-codex-agents.py"
HARNESS_TMP="$(mktemp -d)"
trap 'rm -rf "$HARNESS_TMP"' EXIT

run() { # run WANT LABEL REPO ARGS...
  local want=$1 label=$2 repo=$3 got
  shift 3
  python3 -I "$SYNC" --repo "$repo" --manifest "$repo/kit/seats/codex-agents.manifest.toml" "$@" >"$HARNESS_TMP/out" 2>&1
  got=$?
  if [ "$got" = "$want" ]; then PASS=$((PASS + 1)); else
    FAIL=$((FAIL + 1)); echo "FAIL: $label (want $want, got $got)"; sed 's/^/    /' "$HARNESS_TMP/out"; fi
}
contains() { if grep -qF -- "$2" "$HARNESS_TMP/out"; then PASS=$((PASS + 1)); else FAIL=$((FAIL + 1)); echo "FAIL: $1"; fi; }

run 0 "the repository's contracts are in sync" "$KIT_ROOT" --check

fresh() { # fresh NAME: a scratch copy of the inputs and outputs
  local d="$HARNESS_TMP/$1"
  mkdir -p "$d/.claude/agents" "$d/.codex/agents" "$d/kit/seats"
  cp "$KIT_ROOT"/.claude/agents/*.md "$d/.claude/agents/"
  cp "$KIT_ROOT"/.codex/agents/*.toml "$d/.codex/agents/"
  cp "$KIT_ROOT/kit/seats/codex-agents.manifest.toml" "$d/kit/seats/"
  echo "$d"
}

D="$(fresh drift)"
printf '\nOne more line.\n' >> "$D/.claude/agents/worker.md"
run 1 "an edited source is drift" "$D" --check
contains "drift is named" "drift in .codex/agents/worker.toml"
run 0 "--write repairs drift" "$D" --write
run 0 "and --check agrees" "$D" --check

D="$(fresh unclassified)"
sed 's/^name: worker$/name: intern/' "$D/.claude/agents/worker.md" > "$D/.claude/agents/intern.md"
run 1 "an unclassified agent is refused" "$D" --check
contains "the agent is named" "not classified in the manifest: intern"

D="$(fresh denied)"
printf '\nUse SendMessage to report.\n' >> "$D/.claude/agents/qa.md"
run 1 "a deny phrase is refused" "$D" --check
contains "the phrase is named" "denied phrase 'SendMessage'"

D="$(fresh stale)"
printf '# GENERATED by kit/seats/sync-codex-agents.py from .claude/agents/old.md. Do not edit.\n' > "$D/.codex/agents/old.toml"
printf 'name = "hand-written"\n' > "$D/.codex/agents/custom.toml"
run 1 "a stale generated file is refused" "$D" --check
run 0 "--write removes only generated stale files" "$D" --write
[ ! -e "$D/.codex/agents/old.toml" ] && [ -e "$D/.codex/agents/custom.toml" ] && PASS=$((PASS + 1)) || { FAIL=$((FAIL + 1)); echo "FAIL: stale removal"; }

D="$(fresh missing)"
rm "$D/.codex/agents/reviewer.toml"
run 1 "a missing contract is refused" "$D" --check

D="$(fresh model)"
sed -i 's/^model: sonnet$/model: unmapped/' "$D/.claude/agents/qa.md"
run 1 "an unmapped model is refused" "$D" --check

# Rendered contracts parse as TOML and carry the mapped model and sandbox.
python3 -I - "$KIT_ROOT" <<'PY' && PASS=$((PASS + 1)) || { FAIL=$((FAIL + 1)); echo "FAIL: TOML shape"; }
import sys, tomllib, pathlib
root = pathlib.Path(sys.argv[1])
for p in (root / ".codex" / "agents").glob("*.toml"):
    data = tomllib.loads(p.read_text())
    assert set(data) == {"name", "description", "model", "sandbox_mode", "developer_instructions"}, p
    assert data["sandbox_mode"] in ("read-only", "workspace-write"), p
reviewer = tomllib.loads((root / ".codex/agents/reviewer.toml").read_text())
assert reviewer["sandbox_mode"] == "read-only"
git_manager = tomllib.loads((root / ".codex/agents/git-manager.toml").read_text())
assert git_manager["sandbox_mode"] == "workspace-write"
PY

summary "sync-codex-agents"
