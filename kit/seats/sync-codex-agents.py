#!/usr/bin/env python3
"""Render Codex role contracts from the canonical Claude Code agent definitions.

The Claude side is the single source of truth: `.claude/agents/<name>.md` (YAML
frontmatter plus a Markdown body). This script renders `.codex/agents/<name>.toml`
for every agent the manifest includes, so both seats run the same contract and
nobody edits two copies by hand.

  sync-codex-agents.py --write   render (and remove stale generated files)
  sync-codex-agents.py --check   exit 1 on any drift; used by the gate

What --check refuses:
  * an agent that the manifest neither includes nor excludes (with a reason)
  * a generated file that differs from what the source would render, or is missing
  * a stale generated file whose source agent is gone or excluded
  * a deny phrase (a Claude-only tool, or a forbidden command) in rendered text
  * an agent model the manifest does not map

Standard library only (tomllib needs Python 3.11 or newer).
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
import tomllib
from pathlib import Path

NAME = re.compile(r"[a-z0-9][a-z0-9-]*\Z")
HEADER = "# GENERATED by kit/seats/sync-codex-agents.py from .claude/agents/{name}.md. Do not edit.\n"


class SyncError(Exception):
    pass


def split_frontmatter(text: str, source: Path):
    m = re.match(r"\A---\n(.*?)\n---\n(.*)\Z", text, re.S)
    if not m:
        raise SyncError(f"{source}: expected YAML frontmatter")
    fields = {}
    for line in m.group(1).splitlines():
        if ":" in line:
            key, value = line.split(":", 1)
            fields[key.strip()] = value.strip()
    for key in ("name", "description", "model", "tools"):
        if not fields.get(key):
            raise SyncError(f"{source}: frontmatter lacks {key}")
    return fields, m.group(2).strip()


def toml_basic(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def toml_multiline(value: str) -> str:
    return '"""\n' + value.replace("\\", "\\\\").replace('"""', '""\\"') + '\n"""'


def render_agent(fields, body, manifest):
    models = manifest["models"]
    if fields["model"] not in models:
        raise SyncError(f"agent {fields['name']}: model {fields['model']!r} has no mapping in [models]")
    for old, new in manifest.get("rewrites", {}).items():
        body = body.replace(old, new)
    tools = {t.strip().lower() for t in fields["tools"].split(",")}
    writes = bool(tools & {"write", "edit"}) or fields["name"] in manifest["agents"].get("workspace_write", {})
    return (HEADER.format(name=fields["name"])
            + f"name = {toml_basic(fields['name'])}\n"
            + f"description = {toml_basic(fields['description'])}\n"
            + f"model = {toml_basic(models[fields['model']])}\n"
            + f"sandbox_mode = {toml_basic('workspace-write' if writes else 'read-only')}\n"
            + f"developer_instructions = {toml_multiline(body)}\n")


def plan(repo: Path, manifest: dict):
    included = manifest["agents"]["included"]
    excluded = manifest["agents"]["excluded"]
    for name in list(included) + list(excluded):
        if not NAME.match(name):
            raise SyncError(f"invalid agent name in manifest: {name!r}")
    both = set(included) & set(excluded)
    if both:
        raise SyncError(f"agents both included and excluded: {', '.join(sorted(both))}")
    sources = sorted((repo / ".claude" / "agents").glob("*.md"))
    names = {p.stem for p in sources}
    unclassified = names - set(included) - set(excluded)
    if unclassified:
        raise SyncError("agents not classified in the manifest: " + ", ".join(sorted(unclassified)))
    missing = set(included) - names
    if missing:
        raise SyncError("manifest includes agents with no source: " + ", ".join(sorted(missing)))
    out = {}
    for src in sources:
        if src.stem not in included:
            continue
        fields, body = split_frontmatter(src.read_text(encoding="utf-8"), src)
        if fields["name"] != src.stem:
            raise SyncError(f"{src}: name {fields['name']!r} does not match the file name")
        text = render_agent(fields, body, manifest)
        for phrase in manifest.get("deny_phrases", []):
            if phrase in text:
                raise SyncError(f"agent {src.stem}: rendered contract contains the denied phrase {phrase!r}")
        out[repo / ".codex" / "agents" / f"{src.stem}.toml"] = text
    return out


def generated(directory: Path):
    if not directory.is_dir():
        return set()
    return {p for p in directory.glob("*.toml")
            if p.read_text(encoding="utf-8", errors="replace").startswith("# GENERATED by kit/seats/")}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    ap.add_argument("--repo", type=Path)
    ap.add_argument("--manifest", type=Path)
    args = ap.parse_args(argv)
    repo = args.repo or Path(subprocess.run(["git", "rev-parse", "--show-toplevel"], stdout=subprocess.PIPE,
                                            check=True, text=True).stdout.strip())
    manifest_path = args.manifest or repo / "kit" / "seats" / "codex-agents.manifest.toml"
    try:
        with manifest_path.open("rb") as f:
            manifest = tomllib.load(f)
        expected = plan(repo, manifest)
    except (SyncError, OSError, tomllib.TOMLDecodeError) as e:
        print(f"codex-agents: {e}", file=sys.stderr)
        return 1
    out_dir = repo / ".codex" / "agents"
    stale = generated(out_dir) - set(expected)
    if args.write:
        out_dir.mkdir(parents=True, exist_ok=True)
        for path, text in expected.items():
            path.write_text(text, encoding="utf-8")
        for path in stale:
            path.unlink()
        print(f"codex-agents: wrote {len(expected)} contracts, removed {len(stale)} stale")
        return 0
    problems = []
    for path, text in sorted(expected.items()):
        if not path.exists():
            problems.append(f"missing {path.relative_to(repo)}")
        elif path.read_text(encoding="utf-8") != text:
            problems.append(f"drift in {path.relative_to(repo)} (run --write)")
    problems += [f"stale {p.relative_to(repo)}" for p in sorted(stale)]
    for p in problems:
        print(f"codex-agents: {p}", file=sys.stderr)
    if not problems:
        print(f"codex-agents: {len(expected)} contracts in sync")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
